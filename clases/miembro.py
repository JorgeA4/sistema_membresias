class Miembro:
    def __init__(self, num, nombre, primer_apellido, segundo_apellido, telefono, correo, contraseña, fecha_registro):
        self.num = num
        self.nombre = nombre
        self.primer_apellido = primer_apellido
        self.segundo_apellido = segundo_apellido
        self.telefono = telefono
        self.correo = correo
        self.contraseña = contraseña
        self.fecha_registro = fecha_registro
